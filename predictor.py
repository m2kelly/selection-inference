        def effective_mu_into_target(initial_freqs, target, T):
            """
            Average mutation rate into target over T generations,
            accounting for changing composition of the non-target background.

            This uses the expected neutral mutation dynamics.
            """

            T = max(1, int(round(T)))

            n = len(alleles)

            # Block matrix trick:
            #
            # top-right block of B^T =
            #
            # I + P + ... + P^(T-1)
            #
            B = np.zeros((2*n, 2*n))

            B[:n, :n] = P_mut
            B[:n, n:] = np.eye(n)
            B[n:, n:] = np.eye(n)

            BT = np.linalg.matrix_power(B, T)

            integrated_P = BT[:n, n:]

            initial = np.array([
                initial_freqs.get(x, 0.0)
                for x in alleles
            ])

            # Expected time-integrated frequency of each allele
            occ = initial @ integrated_P

            b_idx = base_index[target]

            non_target_occ = (
                occ.sum() - occ[b_idx]
            )

