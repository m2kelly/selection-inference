    def get_mu(self, point, sub_matrix, a=None, b=None, return_matrix=False):
        """
        solve for mu_a_b simultaneously for a,b in [A,C,G,T]
        calculating from 4 allele diffusion sub rate
        mu matrix is a dict of dicts with keys A,C,G,T and values the mutation rates
        using non neutral get sub rate-change to use neutral when no s
        """
        def matrix_to_vector(matrix,index_list=False):
            """
            Convert 4x4 dict-of-dicts to 12-vector of off-diagonal entries.
            Order is:
                A->C, A->G, A->T,
                C->A, C->G, C->T,
                G->A, G->C, G->T,
                T->A, T->C, T->G
            """
            out = []
            indexs=[]
            for a in BASES:
                for b in BASES:
                    if a == b:
                        continue
                    out.append(matrix[a][b])
                    indexs.append((a, b))
            if index_list:
                return np.array(out, dtype=float), indexs
            else:
                return np.array(out, dtype=float)

        def vector_to_matrix(vec):
            """
            Convert 12-vector back to 4x4 dict-of-dicts.
            Diagonal entries are set to 0.
            """
            matrix = {
                a: {b: 0.0 for b in BASES}
                for a in BASES
            }

            i = 0
            for a in BASES:
                for b in BASES:
                    if a == b:
                        continue

                    matrix[a][b] = vec[i]
                    i += 1

            return matrix

        sub_vector, index_list = matrix_to_vector(sub_matrix, index_list=True)
        if not np.all(np.isfinite(sub_vector)) or np.any(sub_vector < 0):
            raise ValueError("substitution matrix contains invalid off-diagonal rates")

        positive = sub_vector[sub_vector > 0]
        floor = max(float(positive.min()) * 1e-3, 1e-20) if positive.size else 1e-20
        scale = np.maximum(sub_vector, floor)
        z0 = np.log10(np.clip(sub_vector, floor, 0.5))
        neutral_fitness = {base: 1.0 for base in BASES}

        def residuals(log_mu_vector):
            mu_matrix = vector_to_matrix(10.0 ** log_mu_vector)
            try:
                guessed = self.get_sub_rate_diffusion_4_allele_renewal_selection(
                    point,
                    mu_matrix,
                    fitness_matrix=neutral_fitness,
                )
                guessed_vector = matrix_to_vector(guessed)
                if not np.all(np.isfinite(guessed_vector)):
                    raise FloatingPointError
                return (guessed_vector - sub_vector) / scale
            except (ArithmeticError, FloatingPointError, ValueError):
                return np.full(12, 1e12)

        solution = least_squares(
            residuals,
            z0,
            bounds=(-20.0, 0.0),
            method="trf",
            x_scale="jac",
            max_nfev=2000,
            ftol=1e-10,
            xtol=1e-10,
            gtol=1e-10,
        )
        if not solution.success or not np.all(np.isfinite(solution.x)):
            raise RuntimeError(
                f"four-allele mutation-rate solve failed for N={point.pop_size}: "
                f"{solution.message}"
            )

        mu_solution = 10.0 ** solution.x
        if return_matrix:
            return vector_to_matrix(mu_solution)
        if a is None or b is None:
            raise ValueError("a and b are required unless return_matrix=True")
        return mu_solution[index_list.index((a, b))]





    def get_mu_2_allele(self, point):
        """
        Solve for (mu_f, mu_b) simultaneously by matching the observed 
        forward and backward substitution rates using a robust expanding 
        global search.

        This replaces brittle 1-D root finding and works even when the
        substitution function is undefined or non-monotonic.
        """

        # ------------------------------------------------------------
        # 1. Construct the system of equations
        # ------------------------------------------------------------
        def system(mu_vec):
            mu_f,mu_b = mu_vec
            """Return F1, F2 = (subf - obsf), (subb - obsb)."""
            try:
                gpf = GPA(mu_f, mu_b, 
                         pop_size=point.pop_size,
                         mean_sub_rate=None,
                         selection_coeff=point.selection_coeff)
                subf = self.get_sub_rate(gpf)
                gpb = GPA(mu_b, mu_f, 
                         pop_size=point.pop_size,
                         mean_sub_rate=None,
                         selection_coeff=point.selection_coeff)
                subb = self.get_sub_rate(gpb)

                return subf - point.mean_sub_rate, subb - point.mue_bckwrds
            

            except Exception:
                return np.inf, np.inf
            
        def system(mu_vec):
            mu_f, mu_b = mu_vec

            # enforce physical domain
            if mu_f <= 0 or mu_b <= 0 or mu_f > 1 or mu_b > 1:
                return np.array([1e20, 1e20])

            try:
                gpf = GPA(mu_f, mu_b,
                        pop_size=point.pop_size,
                        selection_coeff=point.selection_coeff)

                gpb = GPA(mu_b, mu_f,
                        pop_size=point.pop_size,
                        selection_coeff=point.selection_coeff)

                subf = self.get_sub_rate(gpf)
                subb = self.get_sub_rate(gpb)

                if not (np.isfinite(subf) and np.isfinite(subb)):
                    return np.array([1e20, 1e20])

                return np.array([
                    subf - point.mean_sub_rate,
                    subb - point.mue_bckwrds
                ])

            except Exception:
                return np.array([1e20, 1e20])
        x0=(point.mean_sub_rate, point.mue_bckwrds)
        sol = root(system, x0, method='hybr')
        
        return sol.x[0]



